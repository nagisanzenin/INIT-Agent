//! `init-kernel install --from-bundle` (supervise.md §4.8, §3.11.4) under the fake Root: seed
//! mirror, highest-semver tag, lineage refs, the agent clone, a real offline build of a tiny
//! seed crate through `spawn{kind:"build"}`, `store.put`, `promotion{lkg:true}`, `lkg.json`.

mod common;

use common::*;
use init_proto::root_link::ZoneBootReason;
use std::path::Path;
use std::time::Duration;

/// The watchdog bound of every test here (K-FLAKE: 3-10x its normal runtime; init_testkit::watchdog).
const WD: Duration = Duration::from_secs(80);

fn toolchain() -> std::path::PathBuf {
    Path::new(env!("CARGO")).parent().unwrap().parent().unwrap().to_path_buf()
}

#[test]
fn install_imports_the_seed_tag_builds_it_and_reports_the_genesis_lkg() {
    let _wd = init_testkit::watchdog::arm("install_imports_the_seed_tag_builds_it_and_reports_the_genesis_lkg", Duration::from_secs(30));
    let home = test_home("install");
    for d in ["kernel", "root", "lineage", "cache"] {
        std::fs::create_dir_all(home.join(d)).unwrap();
    }
    std::fs::write(
        home.join("kernel/config.toml"),
        format!("[proxy]\ntest_mode = true\n[supervise]\ngit = \"/usr/bin/git\"\n[sandbox]\ntoolchain = \"{}\"\n", toolchain().display()),
    )
    .unwrap();
    // The maintainer's seed: a tiny crate with an `init-body` bin, two tags.
    let src = home.join("cache/seed-src");
    std::fs::create_dir_all(src.join("src")).unwrap();
    std::fs::create_dir_all(src.join("vendor")).unwrap();
    std::fs::write(src.join("vendor/.keep"), "").unwrap();
    std::fs::write(src.join("Cargo.toml"), "[package]\nname = \"init-body\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[workspace]\n").unwrap();
    std::fs::write(src.join("Cargo.lock"), "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"init-body\"\nversion = \"0.1.0\"\n").unwrap();
    std::fs::write(src.join("src/main.rs"), "fn main() { println!(\"v9\"); }\n").unwrap();
    git(&src, &home, &["init", "-q", "-b", "seed"]);
    git(&src, &home, &["add", "."]);
    git(&src, &home, &["commit", "-q", "-m", "seed 0.9"]);
    git(&src, &home, &["tag", "seed-v0.9.0"]);
    std::fs::write(src.join("src/main.rs"), "fn main() { println!(\"v10\"); }\n").unwrap();
    git(&src, &home, &["commit", "-q", "-am", "seed 0.10"]);
    git(&src, &home, &["tag", "seed-v0.10.0"]);
    let s10 = git(&src, &home, &["rev-parse", "HEAD"]);
    let bundle = home.join("kernel/seed-v0.10.0.bundle");
    git(&src, &home, &["bundle", "create", "-q", bundle.to_str().unwrap(), "seed", "--tags"]);

    let fr = FakeRoot::new(&home, Opts { reason: ZoneBootReason::Install, ..Opts::default() });
    let (ctl, pass) = fr.take_kernel_fds();
    let code = kernel_supervise::install::run(&home, ctl, pass, &bundle, None);
    assert_eq!(code, 0, "install failed; build log: {}", std::fs::read_to_string(home.join("state/kernel/logs/install-build.log")).unwrap_or_default());

    let bare = home.join("lineage/body.git");
    assert_eq!(git(&bare, &home, &["rev-parse", "refs/heads/main"]), s10, "the highest-semver tag");
    assert_eq!(git(&bare, &home, &["rev-parse", "refs/heads/lkg"]), s10);
    assert_eq!(git(&bare, &home, &["rev-parse", "refs/upstream/seed-v0.10.0"]), s10);
    assert_eq!(std::fs::read_to_string(bare.join("info/attributes")).unwrap(), "* -export-subst -export-ignore -filter -ident -text -eol -working-tree-encoding\n");
    assert_eq!(git(&home.join("body"), &home, &["rev-parse", "HEAD"]), s10, "body/ is a clone of lineage");
    assert!(git(&home.join("body"), &home, &["remote"]).contains("upstream"));
    // The built seed runs and is the LKG.
    let out = init_testkit::watchdog::output(&mut std::process::Command::new(home.join("bin/init-body"))).unwrap();
    assert_eq!(String::from_utf8_lossy(&out.stdout), "v10\n");
    use std::os::unix::fs::MetadataExt;
    assert_eq!(std::fs::metadata(home.join("bin/init-body")).unwrap().ino(), std::fs::metadata(home.join("bin/init-body.lkg")).unwrap().ino());
    let lkg: serde_json::Value = serde_json::from_slice(&std::fs::read(home.join("state/kernel/lkg.json")).unwrap()).unwrap();
    assert_eq!((lkg["sha"].as_str(), lkg["reason"].as_str()), (Some(s10.as_str()), Some("seed")));
    assert_eq!(lkg["binary_sha256"], sha256_file(&home.join("bin/init-body")).as_str());
    assert!(lkg["lineage_seq"].as_u64().is_some());
    assert!(home.join(format!("lineage/trees/{}/Cargo.toml", &s10[..12])).exists());
    let g = fr.seen.0.lock().unwrap();
    assert_eq!(g.spawns.len(), 1);
    assert_eq!((g.spawns[0].kind.as_str(), g.spawns[0].profile.as_str()), ("build", "build"));
    assert_eq!(g.store_puts.len(), 1);
    let p = g.lineage.iter().find(|l| l.kind == "promotion").unwrap();
    assert_eq!((p.data["lkg"].as_bool(), p.data["sha"].as_str()), (Some(true), Some(s10.as_str())));
    drop(g);
    remove_home(&home);
}

/// Install mode honours `[supervise] build_timeout_cold_s` (it used to build with the 900 s
/// default whatever the config said): a seed whose build script sleeps 30 s, with a grandchild
/// that holds the build's stdout for 30 s, fails at the configured 6 s (time for cargo to start
/// the script). The kill takes cargo's whole process group and the pumps are bounded, so nothing
/// waits for the grandchild.
#[test]
fn install_honours_the_configured_build_timeout() {
    let _wd = init_testkit::watchdog::arm("install_honours_the_configured_build_timeout", WD);
    let home = test_home("install-to");
    for d in ["kernel", "root", "lineage", "cache"] {
        std::fs::create_dir_all(home.join(d)).unwrap();
    }
    std::fs::write(
        home.join("kernel/config.toml"),
        format!("[proxy]\ntest_mode = true\n[supervise]\ngit = \"/usr/bin/git\"\nbuild_timeout_cold_s = 6\n[sandbox]\ntoolchain = \"{}\"\n", toolchain().display()),
    )
    .unwrap();
    let src = home.join("cache/seed-src");
    std::fs::create_dir_all(src.join("src")).unwrap();
    std::fs::create_dir_all(src.join("vendor")).unwrap();
    std::fs::write(src.join("vendor/.keep"), "").unwrap();
    std::fs::write(src.join("Cargo.toml"), "[package]\nname = \"init-body\"\nversion = \"0.1.0\"\nedition = \"2021\"\nbuild = \"build.rs\"\n\n[workspace]\n").unwrap();
    std::fs::write(src.join("Cargo.lock"), "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"init-body\"\nversion = \"0.1.0\"\n").unwrap();
    std::fs::write(
        src.join("build.rs"),
        "fn main() {\n    let _held = std::process::Command::new(\"/bin/sleep\").arg(\"30\").spawn();\n    std::thread::sleep(std::time::Duration::from_secs(30));\n}\n",
    )
    .unwrap();
    std::fs::write(src.join("src/main.rs"), "fn main() {}\n").unwrap();
    git(&src, &home, &["init", "-q", "-b", "seed"]);
    git(&src, &home, &["add", "."]);
    git(&src, &home, &["commit", "-q", "-m", "seed 0.1"]);
    git(&src, &home, &["tag", "seed-v0.1.0"]);
    let bundle = home.join("kernel/seed-v0.1.0.bundle");
    git(&src, &home, &["bundle", "create", "-q", bundle.to_str().unwrap(), "seed", "--tags"]);

    let fr = FakeRoot::new(&home, Opts { reason: ZoneBootReason::Install, ..Opts::default() });
    let (ctl, pass) = fr.take_kernel_fds();
    let t = std::time::Instant::now();
    let code = kernel_supervise::install::run(&home, ctl, pass, &bundle, None);
    assert_eq!(code, 1, "the build must time out");
    assert!(t.elapsed() < Duration::from_secs(25), "bounded by the configured 6 s, not 900 s or the grandchild's 30 s: {:?}", t.elapsed());
    let g = fr.seen.0.lock().unwrap();
    let alert = g.alerts.iter().find(|a| a.code == "install_failed").expect("install_failed alert");
    assert!(alert.message.contains("build_timeout") && alert.message.contains("within 6 s"), "{}", alert.message);
    assert_eq!(g.spawns.len(), 1, "one build");
    assert!(!g.kills.is_empty(), "the timed-out build was killed through the Root");
    drop(g);
    remove_home(&home);
}
