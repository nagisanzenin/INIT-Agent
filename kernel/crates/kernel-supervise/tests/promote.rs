/// A patch against X made the way the evolve skill says: edit in a worktree-like checkout,
/// refresh self.json, `git diff` (nothing committed).
fn evo_patch(w: &World, edit: impl Fn(&Path)) -> String {
    let b = w.home.join("body");
    ag(&b, &w.home, &["checkout", "-q", "-B", "evo-scratch", &w.x]);
    edit(&b);
    selfmap_write(&b, &w.home);
    ag(&b, &w.home, &["add", "-A"]);
    let mut p = ag(&b, &w.home, &["diff", "--cached", &w.x]);
    if !p.ends_with('\n') {
        p.push('\n');
    }
    ag(&b, &w.home, &["reset", "-q", "--hard", &w.x]);
    p
}

