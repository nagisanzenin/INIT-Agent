    assert_eq!(pr["stages"]["G2"]["prefix_hash"], pr["stages"]["G2"]["parent_prefix_hash"]);
    assert!(pr["stages"]["G3"]["commit"].as_str().is_some_and(|c| c.len() == 40));
    assert_eq!(pr["stages"]["G1"]["tools_sha256"], pr["stages"]["G2"]["tools_sha256"]);
    // The notes: quick, promote, g4 on the candidate, redacted.
    let notes = w.notes(&y);
    let kinds: Vec<&str> = notes.iter().filter_map(|n| n["gate_kind"].as_str()).collect();
    assert_eq!(kinds, ["quick", "promote", "g4"], "{notes:?}");
    assert!(notes.iter().all(|n| n["kernel"].get("build_sha256").is_none()));
