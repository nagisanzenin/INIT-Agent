fn base() -> PathBuf {
    let b = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../target/test-homes/w8b");
    std::fs::create_dir_all(&b).unwrap();
    std::fs::canonicalize(b).unwrap()
}

fn fresh_home(c: &str) -> PathBuf {
    let d = base().join(c);
    if d.exists() {
        std::fs::remove_dir_all(&d).unwrap();
    }
    std::fs::create_dir_all(&d).unwrap();
    d
}

fn remove_home(d: &Path) {
    assert!(d.starts_with(base()) && d != base());
    let _ = std::fs::remove_dir_all(d);
}

fn toolchain() -> PathBuf {
    let o = init_testkit::watchdog::output(std::process::Command::new("rustc").args(["--print", "sysroot"])).expect("rustc on PATH");
    PathBuf::from(String::from_utf8(o.stdout).unwrap().trim())
}

/// `kernel-selfmap` in this test's target dir (built once if missing).
fn selfmap_bin() -> PathBuf {
    static ONCE: Once = Once::new();
    let exe = std::env::current_exe().unwrap();
    let debug = exe.parent().unwrap().parent().unwrap().to_path_buf();
    let bin = debug.join("kernel-selfmap");
    ONCE.call_once(|| {
        if !bin.is_file() {
            let st = init_testkit::watchdog::status(std::process::Command::new(env!("CARGO"))
                .args(["build", "--offline", "-p", "kernel-selfmap", "--bin", "kernel-selfmap"])
                .env("CARGO_TARGET_DIR", debug.parent().unwrap())
                .current_dir(Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")))
                .unwrap();
            assert!(st.success(), "building kernel-selfmap");
        }
    });
    bin
}

