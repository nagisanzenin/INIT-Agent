/// A child killed by its own handle when dropped.
struct Proc(Child);
impl Drop for Proc {
    fn drop(&mut self) {
        if self.0.try_wait().ok().flatten().is_none() {
            let _ = self.0.kill();
            let _ = self.0.wait();
        }
    }
}

struct Out {
    code: i32,
    json: Value,
    stdout: String,
    stderr: String,
}

/// Run `initctl <args>` as an outside client (`INIT_KERNEL_SOCK`), killed by its PID at `t`.
fn initctl(home: &Path, args: &[&str], t: Duration) -> Out {
    let mut c = init_testkit::watchdog::spawn(Command::new(helper("initctl", "initctl"))
        .args(args)
        .env_clear()
        .env("PATH", "/usr/bin:/bin")
        .env("HOME", home.join("cache"))
        .env("INIT_KERNEL_SOCK", home.join("run/kernel.sock"))
        .current_dir(home.join("work"))
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped()))
        .unwrap();
    let (mut so, mut se) = (c.stdout.take().unwrap(), c.stderr.take().unwrap());
    let to = std::thread::spawn(move || {
        let mut s = String::new();
        let _ = so.read_to_string(&mut s);
        s
    });
    let te = std::thread::spawn(move || {
        let mut s = String::new();
        let _ = se.read_to_string(&mut s);
        s
    });
    let deadline = Instant::now() + t;
    let status = loop {
        if let Some(s) = c.try_wait().unwrap() {
            break s;
        }
        if Instant::now() > deadline {
            let _ = c.kill();
            break c.wait().unwrap();
        }
        std::thread::sleep(Duration::from_millis(20));
    };
    let stdout = to.join().unwrap();
    let stderr = te.join().unwrap();
    let json = serde_json::from_str(stdout.trim()).unwrap_or(Value::Null);
    Out { code: status.code().unwrap_or(-1), json, stdout, stderr }
}

fn wait_for<T>(what: &str, t: Duration, mut f: impl FnMut() -> Option<T>) -> T {
    let deadline = Instant::now() + t;
    loop {
        if let Some(v) = f() {
            return v;
        }
        assert!(Instant::now() < deadline, "timed out waiting for {what}");
        std::thread::sleep(Duration::from_millis(100));
    }
}

/// `ROOT_HOME/run/owner.sock`, attached with replay.
struct Owner {
    w: UnixStream,
    r: BufReader<UnixStream>,
}

impl Owner {
    fn connect(sock: &Path) -> Owner {
        let s = wait_for("owner.sock", Duration::from_secs(30), || UnixStream::connect(sock).ok());
        s.set_read_timeout(Some(Duration::from_secs(5))).unwrap();
        let mut w = s.try_clone().unwrap();
        w.write_all(b"{\"t\":\"attach\",\"client\":\"wp7b\",\"replay\":true}\n").unwrap();
        Owner { w, r: BufReader::new(s) }
    }

    fn line(&mut self, text: &str) {
        let f = json!({"t": "line", "text": text});
        self.w.write_all(format!("{f}\n").as_bytes()).unwrap();
    }

    /// Read frames until one's text satisfies `pred`.
    fn until(&mut self, what: &str, t: Duration, pred: impl Fn(&str) -> bool) {
        let deadline = Instant::now() + t;
        let mut line = String::new();
        while Instant::now() < deadline {
            line.clear();
            match self.r.read_line(&mut line) {
                Ok(0) => panic!("owner socket closed while waiting for {what}"),
                Ok(_) => {
                    let v: Value = serde_json::from_str(&line).unwrap_or_default();
                    let text = v["text"].as_str().or_else(|| v["frame"]["text"].as_str()).or_else(|| v["display"]["text"].as_str()).unwrap_or("");
                    if pred(text) {
                        return;
                    }
                }
                Err(_) => continue, // read timeout: poll again
            }
        }
        panic!("timed out waiting for {what}");
    }
}

/// FIX6: what a client of `run/kernel.sock` saw from the kernel's spawn on (ms since `t0`).
#[derive(Debug, Default)]
struct SockTimeline {
    /// The first successful `connect`.
    accepting_ms: Option<u128>,
    /// The first `ping` answered by the server itself (not `starting`, not `E_RATE`).
    served_ms: Option<u128>,
    /// `E_BUSY{reason:"starting"}` answers before that (each checked for its typed shape).
    starting: u32,
    bad: Vec<String>,
}

/// Poll `sock` from `t0`: connect-only every 5 ms until it accepts, then a `ping` every 100 ms
/// (within the lane's 10 req/s) until the server answers it.
fn watch_socket(sock: PathBuf, t0: Instant, limit: Duration) -> std::thread::JoinHandle<SockTimeline> {
    std::thread::spawn(move || {
        let mut tl = SockTimeline::default();
        while t0.elapsed() < limit {
            if tl.accepting_ms.is_none() {
                if UnixStream::connect(&sock).is_ok() {
                    tl.accepting_ms = Some(t0.elapsed().as_millis());
                    continue;
                }
                std::thread::sleep(Duration::from_millis(5));
                continue;
            }
            let answer = UnixStream::connect(&sock).ok().and_then(|mut c| {
                c.set_read_timeout(Some(Duration::from_secs(10))).ok()?;
                c.write_all(b"{\"args\":{},\"cmd\":\"ping\",\"id\":\"fix6\",\"v\":1}\n").ok()?;
                let mut l = String::new();
                BufReader::new(c).read_line(&mut l).ok()?;
                serde_json::from_str::<Value>(&l).ok()
            });
            match answer {
                Some(v) if v["ok"] == false && v["error"]["data"]["reason"] == "starting" => {
                    tl.starting += 1;
                    if v["id"] != "fix6" || v["error"]["code"] != "E_BUSY" || v["error"]["data"]["retry_after_ms"] != 1000 {
                        tl.bad.push(v.to_string());
                    }
                }
                Some(v) if v["error"]["code"] == "E_RATE" => {}
                Some(v) => {
                    if v["ok"] != true || v["result"]["lane"] != "live" {
                        tl.bad.push(v.to_string());
                    }
                    tl.served_ms = Some(t0.elapsed().as_millis());
                    break;
                }
                None => {}
            }
            std::thread::sleep(Duration::from_millis(100));
        }
        tl
    })
}

