//! G0 on real cargo (kernel/gate.md §3.3; §8 G-02, G-03).
//!
//! Each case writes a fixture body workspace under `kernel/target/test-homes/WP8/<unique>/` with a
//! fresh HOME, CARGO_HOME, TMPDIR and target dir, runs G0 offline through [`DirectSpawner`], and
//! deletes the home by its exact path. The fixture has no dependencies, an empty `vendor/`, a
//! hand-written `Cargo.lock` (version 4, so `--frozen` works), `#![forbid(unsafe_code)]` on every
//! target root, and one integration test.

#![forbid(unsafe_code)]

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::OnceLock;
use std::sync::atomic::{AtomicU32, Ordering};
use std::time::Instant;

use kernel_gate::g0::{self, Action, DirectSpawner, EnvSpec, G0Report, G0Spec, code};
use std::time::Duration;

/// The watchdog bound of every test here (K-FLAKE: 3-10x its normal runtime; init_testkit::watchdog).
const WD: Duration = Duration::from_secs(30);

struct Toolchain {
    bin: PathBuf,
    sdkroot: Option<PathBuf>,
    developer_dir: Option<PathBuf>,
}

fn stdout_line(cmd: &mut Command) -> Option<String> {
    let out = init_testkit::watchdog::output(cmd).ok()?;
    if !out.status.success() {
        return None;
    }
    let s = String::from_utf8(out.stdout).ok()?.trim().to_string();
    (!s.is_empty()).then_some(s)
}

/// `<toolchain bin>` = `rustc --print sysroot` + `/bin`; on macOS, SDKROOT from
/// `xcrun --show-sdk-path` and DEVELOPER_DIR from `xcode-select -p` (supervise.md §3.6.2).
fn toolchain() -> &'static Toolchain {
    static T: OnceLock<Toolchain> = OnceLock::new();
    T.get_or_init(|| {
        let sysroot = stdout_line(Command::new("rustc").args(["--print", "sysroot"]))
            .expect("rustc --print sysroot");
        let bin = PathBuf::from(sysroot).join("bin");
        assert!(
            bin.join("cargo").is_file() && bin.join("cargo-clippy").is_file(),
            "{bin:?}"
        );
        let (sdkroot, developer_dir) = if cfg!(target_os = "macos") {
            (
                stdout_line(Command::new("xcrun").arg("--show-sdk-path")).map(PathBuf::from),
                stdout_line(Command::new("xcode-select").arg("-p")).map(PathBuf::from),
            )
        } else {
            (None, None)
        };
        Toolchain {
            bin,
            sdkroot,
            developer_dir,
        }
    })
}

/// A test home under `kernel/target/test-homes/WP8/`, removed by its exact path on drop.
struct Home {
    dir: PathBuf,
}

const CARGO_TOML: &str = "[package]\nname = \"fixture-body\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n\n\
                          [workspace]\n";
const CARGO_LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n\
                          version = 4\n\n[[package]]\nname = \"fixture-body\"\nversion = \"0.1.0\"\n";
const LIB_RS: &str = "#![forbid(unsafe_code)]\n//! Fixture body.\n\n/// Adds.\npub fn add(a: i32, b: i32) -> i32 {\n    a + b\n}\n";
const MAIN_RS: &str =
    "#![forbid(unsafe_code)]\n\nfn main() {\n    println!(\"{}\", fixture_body::add(1, 2));\n}\n";
const TEST_RS: &str = "#![forbid(unsafe_code)]\n\n#[test]\nfn adds() {\n    assert_eq!(fixture_body::add(1, 2), 3);\n}\n";

impl Home {
    fn new(name: &str) -> Home {
        static N: AtomicU32 = AtomicU32::new(0);
        let n = N.fetch_add(1, Ordering::SeqCst);
        let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("../../target/test-homes/WP8")
            .join(format!("g0it-{name}-{}-{n}", std::process::id()));
        if dir.exists() {
            fs::remove_dir_all(&dir).expect("remove stale test home");
        }
        fs::create_dir_all(&dir).expect("create test home");
        let h = Home { dir };
        h.write("Cargo.toml", CARGO_TOML);
        h.write("Cargo.lock", CARGO_LOCK);
        h.write("src/lib.rs", LIB_RS);
        h.write("src/main.rs", MAIN_RS);
        h.write("tests/basic.rs", TEST_RS);
        fs::create_dir_all(h.src().join("vendor")).unwrap();
        h
    }

    /// The fixture tree (the export root).
    fn src(&self) -> PathBuf {
        self.dir.join("src")
    }

    fn write(&self, rel: &str, text: &str) {
        let p = self.src().join(rel);
        fs::create_dir_all(p.parent().unwrap()).unwrap();
        fs::write(p, text).unwrap();
    }

    fn marker(&self) -> PathBuf {
        self.dir.join("evil-ran")
    }

    /// `evil.sh` in the fixture: creates the marker, then runs the real compiler.
    fn write_evil(&self) {
        use std::os::unix::fs::PermissionsExt;
        let script = format!(
            "#!/bin/sh\ntouch '{}'\nexec \"$@\"\n",
            self.marker().display()
        );
        let p = self.src().join("evil.sh");
        fs::write(&p, script).unwrap();
        fs::set_permissions(&p, fs::Permissions::from_mode(0o755)).unwrap();
    }

    fn env_spec(&self) -> EnvSpec {
        let t = toolchain();
        let out = self.dir.join("out");
        EnvSpec {
            toolchain_bin: t.bin.clone(),
            home: out.join("home"),
            tmpdir: out.join("tmp/"),
            cargo_home: out.join("cargo-home"),
            target_dir: out.join("target"),
            source_date_epoch: 1_760_000_000,
            init_home: self.dir.join("init-home"),
            sdkroot: t.sdkroot.clone(),
            developer_dir: t.developer_dir.clone(),
        }
    }

    fn spec(&self) -> G0Spec {
        let mut s = G0Spec::new(self.src(), self.env_spec(), self.dir.join("logs"));
        s.parent_cargo_toml = Some(CARGO_TOML.to_string());
        s
    }

    fn run(&self) -> G0Report {
        let t0 = Instant::now();
        let r = g0::run(&self.spec(), &DirectSpawner);
        eprintln!(
            "{}: G0 {:?} in {} ms",
            self.dir.display(),
            r.code,
            t0.elapsed().as_millis()
        );
        if !r.pass {
            eprintln!("--- diagnostics ---\n{}\n---", r.diagnostics);
        }
        r
    }
}

impl Drop for Home {
    fn drop(&mut self) {
        assert!(
            self.dir
                .to_string_lossy()
                .contains("/target/test-homes/WP8/g0it-")
        );
        let _ = fs::remove_dir_all(&self.dir);
    }
}

fn step_names(r: &G0Report) -> Vec<&'static str> {
    r.steps.iter().map(|s| s.name).collect()
}

#[test]
fn clean_fixture_passes_every_step() {
    let _wd = init_testkit::watchdog::arm("clean_fixture_passes_every_step", Duration::from_secs(40));
    let h = Home::new("clean");
    let r = h.run();
    assert!(r.pass, "{r:#?}");
    assert_eq!(
        step_names(&r),
        [
            "metadata",
            "build_config",
            "shape",
            "check",
            "clippy",
            "test"
        ]
    );
    for s in &r.steps {
        assert!(s.pass && !s.timed_out, "{s:?}");
        if ["metadata", "check", "clippy", "test"].contains(&s.name) {
            assert_eq!(s.exit, Some(0), "{s:?}");
        }
    }
    assert!(r.diagnostics.is_empty() && r.findings.is_empty());
    assert!(!r.has_ext && !r.build_config_present);
    assert_eq!(r.lints_changed, Some(false));
    let test_log = fs::read_to_string(h.dir.join("logs/test.log")).unwrap();
    assert!(test_log.contains("test adds ... ok"), "{test_log}");
    // the fresh CARGO_HOME stayed inside the test home
    assert!(h.dir.join("out/cargo-home").is_dir());
}

