const G03_CONFIG: &str =
    "[build]\nrustc-wrapper = \"./evil.sh\"\nrustflags = [\"--cap-lints=allow\"]\n";

#[test]
fn g03_build_config_rejected_and_wrapper_never_runs() {
    let _wd = init_testkit::watchdog::arm("g03_build_config_rejected_and_wrapper_never_runs", WD);
    let h = Home::new("g03");
    h.write_evil();
    h.write(".cargo/config.toml", G03_CONFIG);
    let r = h.run();
    assert_eq!(r.code, Some(code::BUILD_CONFIG), "{r:#?}");
    assert_eq!(step_names(&r), ["metadata", "build_config"]);
    assert!(r.build_config_present);
    let details: Vec<&str> = r.findings.iter().map(|f| f.detail.as_str()).collect();
    assert_eq!(details.len(), 2, "{details:?}");
    assert!(
        details.iter().any(|d| d.contains("build.rustc-wrapper")),
        "{details:?}"
    );
    assert!(
        details.iter().any(|d| d.contains("--cap-lints=allow")),
        "{details:?}"
    );
    assert!(!h.marker().exists(), "evil.sh ran");
}

/// Runs every command step of `g0::steps(false)` directly (the policy and shape steps skipped),
/// returning (step, exit code, output) per command, and asserting after each that evil.sh never ran.
fn run_commands_without_policy(h: &Home) -> Vec<(&'static str, Option<i32>, String)> {
    let envv = g0::env(&h.env_spec());
    for d in [
        h.dir.join("out/home"),
        h.dir.join("out/tmp"),
        h.dir.join("out/cargo-home"),
    ] {
        fs::create_dir_all(d).unwrap();
    }
    let mut out = Vec::new();
    for step in g0::steps(false) {
        let Action::Commands { cmds } = &step.action else {
            continue;
        };
        for c in cmds {
            let o = init_testkit::watchdog::output(Command::new(toolchain().bin.join(&c.argv[0]))
                .args(&c.argv[1..])
                .env_clear()
                .envs(envv.iter().map(|(k, v)| (k, v)))
                .current_dir(h.src()))
                .unwrap();
            assert!(
                !h.marker().exists(),
                "evil.sh ran during `{}`",
                c.argv.join(" ")
            );
            let text = format!(
                "{}{}",
                String::from_utf8_lossy(&o.stdout),
                String::from_utf8_lossy(&o.stderr)
            );
            out.push((step.name, o.status.code(), text));
        }
    }
    out
}

/// G-03, second half: with the policy skipped, the env's empty `RUSTC_WRAPPER` (and friends) keeps
/// a configured `rustc-wrapper` from ever running, in every step (cargo 1.97.1), and clippy still
/// fails on a warning.
#[test]
fn g03_empty_wrapper_env_keeps_evil_sh_inert_without_the_policy() {
    let _wd = init_testkit::watchdog::arm("g03_empty_wrapper_env_keeps_evil_sh_inert_without_the_policy", Duration::from_secs(50));
    let h = Home::new("g03-inert");
    h.write_evil();
    h.write(
        ".cargo/config.toml",
        "[build]\nrustc-wrapper = \"./evil.sh\"\n",
    );
    h.write("src/main.rs", "#![forbid(unsafe_code)]\n\nfn main() {\n    println!(\"{}\", f());\n}\n\nfn f() -> i32 {\n    return 1;\n}\n");
    let res = run_commands_without_policy(&h);
    let by = |n: &str| res.iter().find(|(s, _, _)| *s == n).unwrap();
    assert_eq!(by("metadata").1, Some(0), "{}", by("metadata").2);
    assert_eq!(by("check").1, Some(0), "{}", by("check").2);
    let clippy = by("clippy");
    assert_ne!(
        clippy.1,
        Some(0),
        "clippy must fail on the warning: {}",
        clippy.2
    );
    assert!(
        clippy.2.contains("unneeded `return` statement"),
        "{}",
        clippy.2
    );
    assert_eq!(by("test").1, Some(0), "{}", by("test").2);
    assert!(!h.marker().exists());

    // Control: the same config without the gate's env does run the wrapper (so the test is real).
    let o = init_testkit::watchdog::output(Command::new(toolchain().bin.join("cargo"))
        .args(["check", "--frozen", "--message-format", "short"])
        .env_clear()
        .envs(
            g0::env(&h.env_spec())
                .into_iter()
                .filter(|(k, _)| !k.contains("WRAPPER")),
        )
        .env("CARGO_TARGET_DIR", h.dir.join("out/target-control"))
        .current_dir(h.src()))
        .unwrap();
    assert!(o.status.success(), "{}", String::from_utf8_lossy(&o.stderr));
    assert!(
        h.marker().exists(),
        "control: without the empty wrapper env, cargo runs evil.sh"
    );
}

/// Why step 2 exists: with the policy skipped, `--cap-lints=allow` in the tree's rustflags makes
/// `clippy -D warnings` pass on code with a warning (cargo 1.97.1).
#[test]
fn g03_cap_lints_would_silence_clippy_without_the_policy() {
    let _wd = init_testkit::watchdog::arm("g03_cap_lints_would_silence_clippy_without_the_policy", WD);
    let h = Home::new("g03-caplints");
    h.write(
        ".cargo/config.toml",
        "[build]\nrustflags = [\"--cap-lints=allow\"]\n",
    );
    h.write("src/main.rs", "#![forbid(unsafe_code)]\n\nfn main() {\n    println!(\"{}\", f());\n}\n\nfn f() -> i32 {\n    return 1;\n}\n");
    let res = run_commands_without_policy(&h);
    let clippy = res.iter().find(|(s, _, _)| *s == "clippy").unwrap();
    assert_eq!(clippy.1, Some(0), "{}", clippy.2);
    // and G0 itself rejects the tree at step 2
    let r = h.run();
    assert_eq!(r.code, Some(code::BUILD_CONFIG), "{r:#?}");
}

#[test]
fn clippy_warning_fails_clippy() {
    let _wd = init_testkit::watchdog::arm("clippy_warning_fails_clippy", WD);
    let h = Home::new("clippy");
    h.write("src/main.rs", "#![forbid(unsafe_code)]\n\nfn main() {\n    println!(\"{}\", f());\n}\n\nfn f() -> i32 {\n    return 1;\n}\n");
    let r = h.run();
    assert_eq!(r.code, Some(code::CLIPPY), "{r:#?}");
    assert_eq!(r.step, Some("clippy"));
    assert_eq!(
        step_names(&r),
        ["metadata", "build_config", "shape", "check", "clippy"]
    );
    assert_ne!(r.steps.last().unwrap().exit, Some(0));
    assert!(
        r.diagnostics.starts_with("src/main.rs:"),
        "{}",
        r.diagnostics
    );
    assert!(
        r.diagnostics.contains("error: unneeded `return` statement"),
        "{}",
        r.diagnostics
    );
    assert!(r.diagnostics.len() <= g0::DIAG_CAP);
    let log = fs::read_to_string(h.dir.join("logs/clippy.log")).unwrap();
    assert!(
        log.contains("Checking fixture-body"),
        "the full log keeps cargo's progress lines"
    );
}

