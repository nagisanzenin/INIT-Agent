def run_driver():
    path = os.path.join(SCRATCH, "stencil_driver.py")
    out = os.path.join(SCRATCH, "stencil_driver.json")
    with open(path, "w") as f:
        f.write(DRIVER)
    cases = []
    for name, rows in ITEMS:
        for k, (tpl, ctx, _) in enumerate(rows):
            cases.append(["%s#%d" % (name, k), tpl, ctx])
    try:
        subprocess.run([sys.executable, "-S", "-s", "-B", path, out], cwd=SCRATCH, env=ENV,
                       input=json.dumps(cases).encode("utf-8"), stdout=subprocess.DEVNULL,
                       stderr=subprocess.DEVNULL, timeout=20)
        with open(out) as f:
            data = json.load(f)
        return data["res"] or {}, data["meta"]
    except Exception:
        return {}, {"te_is_exception": False, "mutated": ["?"]}


def case_ok(got, exp):
    if not isinstance(got, list) or not got:
        return False
    if exp[0] == "ok":
        return got == ["ok", exp[1]]
    if len(got) < 6 or got[0] != "err" or got[1] != "TemplateError" or got[2] != exp[1]:
        return False
    if len(exp) > 2:
        return got[3:6] == list(exp[2:5])
    return True


def run_cli():
    d = os.path.join(SCRATCH, "cli")
    os.makedirs(d, exist_ok=True)
    for name, text in CLI_FILES.items():
        with open(os.path.join(d, name), "wb") as f:
            f.write(text.encode("utf-8"))
    results = {}
    for item, rows in CLI_ITEMS:
        ok = True
        for args, code, out, err in rows:
            try:
                p = subprocess.run([sys.executable, "-S", "-s", "-B", "-m", "stencil"] + args, cwd=d, env=ENV,
                                   stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                   timeout=10)
                ok = ok and (p.returncode, p.stdout, p.stderr) == (code, out, err)
            except Exception:
                ok = False
        results[item] = ok
    return results


def main():
    res, meta = run_driver()
    verdict = {}
    for name, rows in ITEMS:
        ok = all(case_ok(res.get("%s#%d" % (name, k)), exp) for k, (_, _, exp) in enumerate(rows))
        if name == "r02_error_object":
            ok = ok and meta.get("te_is_exception") is True and meta.get("mutated") == []
        verdict[name] = ok
    verdict.update(run_cli())
    for name in NAMES:
        print("%s %s" % ("PASS" if verdict.get(name) else "FAIL", name))


main()
