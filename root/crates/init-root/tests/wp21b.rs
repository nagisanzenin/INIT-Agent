//! WP21b integration tests: the install path (root/root.md §4.3 steps 7–8). `init-root install
//! --seed-source` bundles the seed into `INIT_HOME/kernel/seed/<tag>.bundle`, runs the **real** kernel in
//! install mode in the zone (`init-kernel install --from-bundle`, kernel profile; its seed build under the
//! `build` profile through the Root's broker), and forms the genesis tuple from the kernel's
//! `promotion{lkg:true}`: the installed kernel, the body built from the seed, its extension set.
//! Run with `cargo test --offline -p init-root --features test-fixtures`.
//!
//! The kernel is `kernel/target/k1/debug/init-kernel` (or `INIT_KERNEL_BIN`), copied into the test home
//! first; the test is skipped when neither exists. The seed is a tiny crate with no dependencies, so the
//! sandboxed build takes seconds. `install` runs with the owner's real `HOME`, because the class rules
//! compare the kernel's passwd home (`HOME_REAL`) with the Root's, and with `--no-service`, so nothing is
//! written under it. Every process here is the test's own `init-root` or one that Root spawned and holds.
#![cfg(feature = "test-fixtures")]

use serde_json::Value;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};

const BIN: &str = env!("CARGO_BIN_EXE_init-root");

fn base(name: &str) -> PathBuf {
    let b = fs::canonicalize(Path::new(env!("CARGO_MANIFEST_DIR")).join("../../target")).unwrap().join("test-homes/wp21b");
    let d = b.join(name);
    if d.exists() {
        fs::remove_dir_all(&d).unwrap(); // exact path, created by an earlier run of this test
    }
    fs::create_dir_all(&d).unwrap();
    d
}

fn real_home() -> PathBuf {
    // SAFETY: getpwuid returns a pointer into static storage or null; read at once.
    unsafe {
        let pw = libc::getpwuid(libc::getuid());
        assert!(!pw.is_null());
        PathBuf::from(std::ffi::CStr::from_ptr((*pw).pw_dir).to_str().unwrap())
    }
}

/// The rustup toolchain this test was built with (`$TOOLCHAIN`), canonical.
fn toolchain() -> PathBuf {
    fs::canonicalize(Path::new(env!("CARGO")).parent().unwrap().parent().unwrap()).unwrap()
}

fn git(dir: &Path, args: &[&str]) -> String {
    let o = Command::new("/usr/bin/git").current_dir(dir).env_clear().env("PATH", "/usr/bin:/bin").env("HOME", dir)
        .env("GIT_CONFIG_NOSYSTEM", "1").env("GIT_CONFIG_GLOBAL", "/dev/null")
        .env("GIT_AUTHOR_DATE", "2026-10-20T00:00:00Z").env("GIT_COMMITTER_DATE", "2026-10-20T00:00:00Z")
        .args(["-c", "user.name=maintainer", "-c", "user.email=m@init.invalid", "-c", "commit.gpgsign=false", "-c", "tag.gpgsign=false"])
        .args(args).output().unwrap();
    assert!(o.status.success(), "git {args:?}: {}", String::from_utf8_lossy(&o.stderr));
    String::from_utf8_lossy(&o.stdout).trim().to_string()
}

/// The maintainer's seed: a crate `init-body` (no dependencies, an empty `vendor/`), GENESIS.md, on branch
/// `seed` with tags seed-v0.9.0 and seed-v0.10.0 (semver, not lexical, picks the second). Returns its sha.
fn seed_repo(src: &Path) -> String {
    fs::create_dir_all(src.join("src")).unwrap();
    fs::create_dir_all(src.join("vendor")).unwrap();
    fs::create_dir_all(src.join(".cargo")).unwrap();
    fs::write(src.join("vendor/.keep"), "").unwrap();
    fs::write(src.join(".cargo/config.toml"), "[source.crates-io]\nreplace-with = \"vendored-sources\"\n[source.vendored-sources]\ndirectory = \"vendor\"\n[net]\noffline = true\n").unwrap();
    fs::write(src.join("Cargo.toml"), "[package]\nname = \"init-body\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[workspace]\n").unwrap();
    fs::write(src.join("Cargo.lock"), "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"init-body\"\nversion = \"0.1.0\"\n").unwrap();
    fs::write(src.join("GENESIS.md"), "# Genesis\n").unwrap();
    fs::write(src.join("src/main.rs"), "fn main() { println!(\"seed 0.9\"); }\n").unwrap();
    git(src, &["init", "-q", "-b", "seed"]);
    git(src, &["add", "-A"]);
    git(src, &["commit", "-q", "-m", "seed 0.9"]);
    git(src, &["tag", "seed-v0.9.0"]);
    fs::write(src.join("src/main.rs"), "fn main() { println!(\"seed 0.10\"); }\n").unwrap();
    git(src, &["commit", "-q", "-am", "seed 0.10"]);
    git(src, &["tag", "seed-v0.10.0"]);
    git(src, &["checkout", "-q", "-b", "elsewhere"]); // the bundle takes branch `seed`, not HEAD
    fs::write(src.join("src/main.rs"), "fn main() { println!(\"not the seed\"); }\n").unwrap();
    git(src, &["commit", "-q", "-am", "not the seed"]);
    git(src, &["rev-parse", "seed-v0.10.0^{commit}"])
}

fn charter() -> &'static str {
    "schema_version = 1\n[purpose]\ntext = \"WP21b install test home.\"\n[autonomy]\nmax_level = 4\n[quotas]\ndisk_min_free_gib = 0\n\
     [root]\ntest_mode = true\nhb_interval_s = 1\nkernel_hello_timeout_s = 30\n"
}

fn install(d: &Path, home: &Path, args: &[&str]) -> Output {
    Command::new(BIN).env_clear().env("HOME", home).env("INIT_ROOT_HOME", d.join("rh")).env("INIT_HOME", d.join("ih"))
        .env("PATH", "/usr/bin:/bin").arg("install").args(args).stdin(Stdio::null()).output().unwrap()
}

fn records(rh: &Path) -> Vec<Value> {
    fs::read_to_string(rh.join("lineage/lineage.jsonl")).unwrap_or_default().lines().map(|l| serde_json::from_str(l).unwrap()).collect()
}

fn sha256(p: &Path) -> String {
    let o = Command::new("/usr/bin/shasum").args(["-a", "256"]).arg(p).output().unwrap();
    String::from_utf8_lossy(&o.stdout).split_whitespace().next().unwrap().to_string()
}

/// A seed source without branch `seed` (or a file that is no bundle) is refused before any kernel runs,
/// and install.json is removed again, so `install` can be re-run.
#[test]
fn a_bad_seed_source_is_refused_and_install_can_be_rerun() {
    let d = base("bad");
    let src = d.join("src");
    fs::create_dir_all(&src).unwrap();
    fs::write(src.join("a"), "a").unwrap();
    git(&src, &["init", "-q", "-b", "main"]);
    git(&src, &["add", "-A"]);
    git(&src, &["commit", "-q", "-m", "x"]);
    fs::create_dir_all(d.join("rh")).unwrap();
    fs::write(d.join("charter.toml"), charter()).unwrap();
    let ch = d.join("charter.toml");
    let tc = toolchain();
    let args = |s: &Path| vec!["--charter".to_string(), ch.display().to_string(), "--toolchain".into(), tc.display().to_string(),
        "--seed-source".into(), s.display().to_string(), "--no-service".into()];
    let a: Vec<String> = args(&src);
    let o = install(&d, &d, &a.iter().map(String::as_str).collect::<Vec<_>>());
    let err = String::from_utf8_lossy(&o.stderr);
    assert_eq!(o.status.code(), Some(1), "{err}");
    assert!(err.contains("seed install failed") && err.contains("seed"), "{err}");
    assert!(!d.join("rh/install.json").exists(), "install.json is removed after a failed seed step");
    assert_eq!(fs::read_dir(d.join("ih/kernel/seed")).unwrap().count(), 0, "no bundle or temp file is left");
    let junk = d.join("junk.bundle");
    fs::write(&junk, "not a bundle\n").unwrap();
    let a: Vec<String> = args(&junk);
    let o = install(&d, &d, &a.iter().map(String::as_str).collect::<Vec<_>>());
    assert_eq!(o.status.code(), Some(1), "a re-run reaches the seed step again: {}", String::from_utf8_lossy(&o.stderr));
    assert!(String::from_utf8_lossy(&o.stderr).contains("not a git bundle"));
    assert_eq!(fs::read_dir(d.join("ih/kernel/seed")).unwrap().count(), 0);
    fs::remove_dir_all(&d).unwrap();
}

/// §4.3 steps 7–8 with the real kernel: the genesis tuple has a real seed sha and the built body; body/
/// is a clone holding the seed files; lkg.json agrees; nothing is left running.
#[test]
fn install_runs_the_kernel_in_install_mode_and_forms_the_genesis_tuple() {
    let kernel = std::env::var_os("INIT_KERNEL_BIN").map(PathBuf::from)
        .unwrap_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../kernel/target/k1/debug/init-kernel"));
    if !kernel.is_file() {
        eprintln!("skipped: no init-kernel at {} (set INIT_KERNEL_BIN)", kernel.display());
        return;
    }
    let d = base("seed");
    let (rel, src) = (d.join("rel"), d.join("src"));
    fs::create_dir_all(&rel).unwrap();
    let st = Command::new("/bin/cp").arg("-c").arg(&kernel).arg(rel.join("init-kernel")).status().unwrap(); // a frozen APFS clone
    assert!(st.success());
    let seed_sha = seed_repo(&src);
    fs::create_dir_all(d.join("rh")).unwrap();
    fs::write(d.join("charter.toml"), charter()).unwrap();
    let (ch, tc) = (d.join("charter.toml"), toolchain());
    let o = install(&d, &real_home(), &["--release", rel.to_str().unwrap(), "--charter", ch.to_str().unwrap(), "--toolchain",
        tc.to_str().unwrap(), "--seed-source", src.to_str().unwrap(), "--no-service"]);
    let (out, err) = (String::from_utf8_lossy(&o.stdout), String::from_utf8_lossy(&o.stderr));
    let (rh, ih) = (d.join("rh"), d.join("ih"));
    assert_eq!(o.status.code(), Some(0), "install: {out}\n{err}\nkernel log: {}\nbuild log: {}",
        fs::read_to_string(rh.join("logs/kernel-1.stderr")).unwrap_or_default(),
        fs::read_to_string(ih.join("state/kernel/logs/install-build.log")).unwrap_or_default());
    assert!(out.contains("seed seed-v0.10.0 installed: genesis tuple t") && out.contains("no service file"), "{out}");
    // step 7: the bundle, named by the tag the kernel installs
    assert!(ih.join("kernel/seed/seed-v0.10.0.bundle").is_file());
    // the kernel's part: mirror, lineage, the agent's clone, the built body
    assert_eq!(git(&ih.join("lineage/body.git"), &["rev-parse", "refs/heads/main"]), seed_sha);
    assert_eq!(git(&ih.join("lineage/body.git"), &["rev-parse", "refs/heads/lkg"]), seed_sha);
    assert_eq!(git(&ih.join("lineage/seed.git"), &["rev-parse", "refs/heads/seed"]), seed_sha);
    assert_eq!(git(&ih.join("body"), &["rev-parse", "HEAD"]), seed_sha, "body/ is a clone of lineage at the seed tag");
    assert_eq!(fs::read_to_string(ih.join("body/GENESIS.md")).unwrap(), "# Genesis\n");
    let run = Command::new(ih.join("bin/init-body")).output().unwrap();
    assert_eq!(String::from_utf8_lossy(&run.stdout), "seed 0.10\n", "built from the tag, not from another branch");
    let body_sha256 = sha256(&ih.join("bin/init-body"));
    // step 8: the records and the genesis tuple
    let recs = records(&rh);
    let kinds: Vec<&str> = recs.iter().map(|r| r["kind"].as_str().unwrap()).collect();
    let at = |k: &str| kinds.iter().position(|x| *x == k).unwrap_or_else(|| panic!("no {k} record in {kinds:?}"));
    assert!(at("genesis") < at("charter") && at("charter") < at("promotion") && at("promotion") < at("tuple"), "{kinds:?}");
    assert_eq!(&kinds[at("tuple")..], ["tuple", "lkg", "audited"], "{kinds:?}");
    let promo = &recs[at("promotion")];
    assert_eq!((promo["data"]["sha"].as_str(), promo["data"]["lkg"].as_bool()), (Some(seed_sha.as_str()), Some(true)));
    let kernel_sha = sha256(&ih.join("kernel/bin/init-kernel"));
    assert_eq!(promo["by"].as_str(), Some(format!("kernel:{}", &kernel_sha[..12]).as_str()), "signed as the installed kernel");
    let t = &recs[at("tuple")]["data"];
    let id = t["id"].as_str().unwrap();
    assert_eq!(t["tuple"]["body"]["sha"].as_str(), Some(seed_sha.as_str()), "a real seed sha, not \"\"");
    assert_eq!(t["tuple"]["body"]["binary"].as_str(), Some(body_sha256.as_str()));
    assert_eq!(t["tuple"]["kernel"]["init_kernel"].as_str(), Some(kernel_sha.as_str()));
    assert_eq!(t["tuple"]["kernel"]["source"].as_str(), Some("maintainer"));
    assert_eq!((t["tuple"]["ext"]["components"].as_array().map(Vec::len), &t["tuple"]["ext"]["set"]), (Some(0), &Value::Null));
    assert_eq!((recs[at("lkg")]["data"]["tuple"].as_str(), recs[at("audited")]["data"]["tuple"].as_str()), (Some(id), Some(id)));
    assert!(rh.join("store/blobs").join(&body_sha256).is_file() && rh.join("store/blobs").join(&kernel_sha).is_file());
    assert!(rh.join(format!("store/tuples/{id}.json")).is_file());
    // the kernel's lkg.json agrees with the Root's genesis tuple
    let lkg: Value = serde_json::from_str(&fs::read_to_string(ih.join("state/kernel/lkg.json")).unwrap()).unwrap();
    assert_eq!((lkg["sha"].as_str(), lkg["binary_sha256"].as_str(), lkg["reason"].as_str()), (Some(seed_sha.as_str()), Some(body_sha256.as_str()), Some("seed")));
    assert_eq!(lkg["lineage_seq"], promo["seq"]);
    // the kernel config template the install-mode kernel ran with: [sandbox] equals install.json
    let info: Value = serde_json::from_str(&fs::read_to_string(rh.join("install.json")).unwrap()).unwrap();
    let cfg = fs::read_to_string(ih.join("kernel/config.toml")).unwrap();
    assert!(cfg.contains(&format!("toolchain = \"{}\"", info["toolchain"].as_str().unwrap())), "{cfg}");
    // the view and the Root's state: stopped, nothing held, the pointers on genesis
    let state: Value = serde_json::from_str(&fs::read_to_string(rh.join("state/root.json")).unwrap()).unwrap();
    assert_eq!((state["slot"].as_str(), state["instances"].as_array().map(Vec::len)), (Some("stopped"), Some(0)));
    assert_eq!((state["tuples"]["current"].as_str(), state["tuples"]["lkg"].as_str(), state["tuples"]["audited"].as_str()), (Some(id), Some(id), Some(id)));
    let view: Value = serde_json::from_str(&fs::read_to_string(ih.join("root/status.json")).unwrap()).unwrap();
    assert_eq!(view["audited_good"]["body_sha"].as_str(), Some(seed_sha.as_str()));
    assert_eq!(fs::read_dir(ih.join("run/mark")).unwrap().filter(|e| e.as_ref().unwrap().file_name() != "decoy").count(), 0, "every mark is gone");
    // install runs once
    let o = install(&d, &real_home(), &["--release", rel.to_str().unwrap(), "--seed-source", src.to_str().unwrap(), "--no-service"]);
    assert_eq!(o.status.code(), Some(1));
    assert!(String::from_utf8_lossy(&o.stderr).contains("already installed"));
    fs::remove_dir_all(&d).unwrap();
}
